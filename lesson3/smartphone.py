class Smartphone:
    def __init__(self, brand_phone, model_phone, number_phone):
        self.brand_phone = brand_phone
        self.model_phone = model_phone
        self.number_phone = number_phone

    def get_brand_phone(self):
        return self.brand_phone

    def get_model_phone(self):
        return self.model_phone

    def get_number_phone(self):
        return self.number_phone
